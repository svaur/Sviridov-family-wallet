-- Admin panel: a dedicated `admins` table. An admin is a different person from
-- a wallet user — the system sees them separately and an admin cannot sign into
-- the wallet. Plus the user-management columns an admin needs.

CREATE TABLE admins (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             VARCHAR(64)  NOT NULL UNIQUE,
    password_hash        VARCHAR(100) NOT NULL,
    must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active            BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at        TIMESTAMPTZ,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now()
);

ALTER TABLE users
    ADD COLUMN must_change_password BOOLEAN     NOT NULL DEFAULT FALSE,
    ADD COLUMN is_active            BOOLEAN     NOT NULL DEFAULT TRUE,
    ADD COLUMN last_login_at        TIMESTAMPTZ;

-- The epoch is no longer only "password changed": banning, unbanning, a password
-- reset and a forced logout all bump it, so any of them signs out the user's
-- existing sessions. The column name now reflects that wider meaning.
ALTER TABLE users RENAME COLUMN password_changed_at TO session_epoch;
