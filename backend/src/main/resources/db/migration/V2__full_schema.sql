-- Sviridov_family_wallet — full schema (Stage 1).
-- All tables are created upfront; individual fields are activated in later stages.
-- Timestamps are TIMESTAMPTZ (UTC in DB); the UI renders Europe/Moscow.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE cards (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    display_name VARCHAR(120) NOT NULL,
    bank         VARCHAR(120),
    last4        VARCHAR(4),
    currency     VARCHAR(3)   NOT NULL DEFAULT 'RUB',
    archived     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_cards_user_id ON cards (user_id);

CREATE TABLE categories (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    parent_id BIGINT       REFERENCES categories (id) ON DELETE SET NULL,
    name      VARCHAR(120) NOT NULL
);
CREATE INDEX idx_categories_user_id ON categories (user_id);

CREATE TABLE statements (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id               BIGINT      NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    uploaded_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    period_from           DATE,
    period_to             DATE,
    parser_version        VARCHAR(40),
    status                VARCHAR(20) NOT NULL,
    txn_count             INT,
    row_count_raw         INT,
    card_number_extracted VARCHAR(20),
    contract              VARCHAR(120),
    account               VARCHAR(40)
);
CREATE INDEX idx_statements_card_id ON statements (card_id);

CREATE TABLE transactions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    card_id              BIGINT        NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    statement_id         BIGINT        REFERENCES statements (id) ON DELETE SET NULL,
    row_number           INT,
    date                 DATE          NOT NULL,
    operation            VARCHAR(200),
    purpose              TEXT,
    merchant_normalized  VARCHAR(255),
    amount               NUMERIC(15,2) NOT NULL,
    type                 VARCHAR(10)   NOT NULL CHECK (type IN ('debit', 'credit')),
    category_id          BIGINT        REFERENCES categories (id) ON DELETE SET NULL,
    is_transfer          BOOLEAN       NOT NULL DEFAULT FALSE,
    is_excluded          BOOLEAN       NOT NULL DEFAULT FALSE,
    comment              TEXT,
    fingerprint          VARCHAR(64),
    deleted_at           TIMESTAMPTZ,
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_transactions_user_date ON transactions (user_id, date);
CREATE INDEX idx_transactions_card_id ON transactions (card_id);
CREATE INDEX idx_transactions_fingerprint ON transactions (fingerprint);

CREATE TABLE rules (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type         VARCHAR(40) NOT NULL CHECK (type IN ('merchant_contains', 'merchant_regex', 'amount_range', 'day_of_month')),
    params       JSONB       NOT NULL,
    category_id  BIGINT      NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    priority     INT         NOT NULL DEFAULT 0,
    auto_learned BOOLEAN     NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_rules_user_id ON rules (user_id);

CREATE TABLE statement_gaps (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id     BIGINT      NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    gap_from    DATE        NOT NULL,
    gap_to      DATE        NOT NULL,
    detected_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_statement_gaps_card_id ON statement_gaps (card_id);

CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type       VARCHAR(40) NOT NULL,
    payload    JSONB,
    read_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_notifications_user_id ON notifications (user_id);

CREATE TABLE audit_log (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    entity    VARCHAR(40) NOT NULL,
    entity_id BIGINT      NOT NULL,
    action    VARCHAR(20) NOT NULL,
    old_value JSONB,
    new_value JSONB,
    at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_log_user_id ON audit_log (user_id);
